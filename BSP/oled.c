void OLED_DrawPoint(u8 x, u8 y, u8 state)
{
    // 1. 边界校验：x=列(0-127)，y=行(0-63)，超出则直接返回（关键修正！）
    // 错误原写法：x>=127||y>=63 → 正确：x>=128（列最大127）、y>=64（行最大63）
    if (x >= 128 || y >= 64) {
        return;
    }

    // 2. 坐标转换：用y（行）计算OLED页号和页内位（核心修正！）
    // OLED是页寻址：8行=1页，所以行y转页号，列x直接对应显存列
    u8 page = y / 8;    // 行y对应的OLED页号（0-7，比如y=32 → page=4）
    u8 bit  = y % 8;    // 行y在页内的bit位（0-7，比如y=32 → bit=0）

    // 3. 修改显存：列x对应显存的列，页page对应显存的行（核心修正！）
    // 错误原写法：OLED_GRAM[page][y] → 正确：OLED_GRAM[page][x]
    if (state == 1) {
        //OLED_GRAM[page][x] |= (1 << bit);  // 置1：点亮该像素
			  OLED_GRAM[x][page] |= (1 << bit); 
    } else {
        //OLED_GRAM[page][x] &= ~(1 << bit); // 置0：熄灭该像素
			    OLED_GRAM[x][page] &= ~(1 << bit);
    }

    // 4. 写入OLED硬件：定位到列x、页page，写入修改后的显存数据（核心修正！）
    // 错误原写法：OLED_Set_Pos(y, page+YOFFSET) → 正确：OLED_Set_Pos(x, page+YOFFSET)
    OLED_Set_Pos(x, page + YOFFSET);  
    //OLED_WR_Byte(OLED_GRAM[page][x], OLED_DATA);
		OLED_WR_Byte(OLED_GRAM[x][page], OLED_DATA);
}

// m^n函数
u32 oled_pow(u8 m, u8 n)
{
	u32 result = 1;
	while (n--)
		result *= m;
	return result;
}

void OLED_ShowNum(u8 x, u8 y, u32 num, u8 len, u8 size2)
{
	u8 t, temp;
	u8 enshow = 0;
	for (t = 0; t < len; t++)
	{
		temp = (num / oled_pow(10, len - t - 1)) % 10;
		if (enshow == 0 && t < (len - 1))
		{
			if (temp == 0)
			{
				OLED_ShowChar(x + (size2 / 2) * t, y, ' ');
				continue;
			}
			else
				enshow = 1;
		}
		OLED_ShowChar(x + (size2 / 2) * t, y, temp + '0');
	}
}


